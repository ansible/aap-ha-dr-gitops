import time

from ansible.module_utils.basic import AnsibleModule

from ansible_collections.aap.hadr_ops.plugins.module_utils.k8s_helper import (
    create_helper,
)
from ansible_collections.aap.hadr_ops.plugins.module_utils import constants as const


def clear_promotion_token(module, helper, namespace, cluster_name):
    """Remove stale promotionToken from cluster spec."""
    start_time = time.perf_counter()

    patch = [{"op": "remove", "path": "/spec/replica/promotionToken"}]

    # 404 = CR gone, 422 = path doesn't exist in JSON Patch — both OK
    # (token may not be present if this is the first switchover or was already cleared)
    helper.safe_call(
        lambda: helper.patch_custom_resource(
            const.CNPG_GROUP, const.CNPG_VERSION, namespace, const.CNPG_PLURAL, cluster_name,
            body=patch, patch_type="json",
        ),
        tolerate_statuses=(404, 422),
    )

    return {
        'changed': True,
        'operation': 'clear_promotion_token',
        'duration_seconds': time.perf_counter() - start_time,
        'message': 'Promotion token cleared (or did not exist)',
    }


def demote_primary(module, helper, namespace, cluster_name, new_primary,
                   token_wait_timeout, token_poll_interval):
    """Demote the current primary by setting spec.replica.primary.

    Waits for status.demotionToken to appear.
    """
    start_time = time.perf_counter()

    # Step 1: Patch spec.replica.primary to trigger demotion
    patch = {"spec": {"replica": {"primary": new_primary}}}

    try:
        helper.patch_custom_resource(
            const.CNPG_GROUP, const.CNPG_VERSION, namespace, const.CNPG_PLURAL, cluster_name,
            body=patch, patch_type="merge",
        )
    except Exception as exc:
        module.fail_json(
            msg="Failed to patch cluster for demotion: %s" % exc,
            duration_seconds=time.perf_counter() - start_time,
        )

    # Step 2: Poll for status.demotionToken — the CNPG operator generates
    # this after archiving the shutdown checkpoint WAL
    demotion_token = None
    deadline = time.time() + token_wait_timeout

    while time.time() < deadline:
        cr = helper.safe_call(
            lambda: helper.get_custom_resource(
                const.CNPG_GROUP, const.CNPG_VERSION, namespace, const.CNPG_PLURAL, cluster_name,
            ),
        )
        if cr is not None:
            token = cr.get("status", {}).get("demotionToken", "")
            if token:
                demotion_token = token
                break
        time.sleep(token_poll_interval)

    duration = time.perf_counter() - start_time

    if not demotion_token:
        module.fail_json(
            msg="Demotion token not generated within timeout",
            timeout=token_wait_timeout,
            duration_seconds=duration,
        )

    return {
        'changed': True,
        'operation': 'demote',
        'demotion_token': demotion_token,
        'duration_seconds': duration,
        'message': 'Primary demoted, demotion token generated',
    }


def _promote(helper, namespace, cluster_name, patch, reconciliation_wait):
    """Apply a promotion patch and wait for reconciliation.

    Shared by graceful promote and force-promote.
    """
    helper.patch_custom_resource(
        const.CNPG_GROUP, const.CNPG_VERSION, namespace, const.CNPG_PLURAL, cluster_name,
        body=patch, patch_type="merge",
    )
    # Wait for CNPG operator to reconcile the new primary designation
    time.sleep(reconciliation_wait)


def promote_replica(module, helper, namespace, cluster_name, new_primary,
                    promotion_token, reconciliation_wait):
    """Promote the replica to primary using demotion token."""
    start_time = time.perf_counter()

    patch = {
        "spec": {
            "replica": {
                "primary": new_primary,
                "promotionToken": promotion_token,
            }
        }
    }

    try:
        _promote(helper, namespace, cluster_name, patch, reconciliation_wait)
    except Exception as exc:
        module.fail_json(
            msg="Failed to patch cluster for promotion: %s" % exc,
            duration_seconds=time.perf_counter() - start_time,
        )

    return {
        'changed': True,
        'operation': 'promote',
        'duration_seconds': time.perf_counter() - start_time,
        'message': 'Replica promoted to primary with token',
    }


def force_promote_replica(module, helper, namespace, cluster_name,
                          new_primary, reconciliation_wait):
    """Force-promote the replica WITHOUT token (disaster recovery mode)."""
    start_time = time.perf_counter()

    patch = {"spec": {"replica": {"primary": new_primary}}}

    try:
        _promote(helper, namespace, cluster_name, patch, reconciliation_wait)
    except Exception as exc:
        module.fail_json(
            msg="Failed to patch cluster for force-promotion: %s" % exc,
            duration_seconds=time.perf_counter() - start_time,
        )

    return {
        'changed': True,
        'operation': 'force_promote',
        'forced': True,
        'duration_seconds': time.perf_counter() - start_time,
        'warnings': [
            "Force promotion without demotion token - manual intervention required if old primary recovers",
            "If old primary region recovers, delete its CNPG cluster and re-bootstrap as replica",
        ],
        'message': 'Replica force-promoted to primary without token (DR mode)',
    }


def main():
    module = AnsibleModule(
        argument_spec=dict(
            namespace=dict(type='str', required=True),
            cluster_name=dict(type='str', required=True),
            kubeconfig=dict(type='str', default=''),
            context=dict(type='str', default=''),
            operation=dict(
                type='str',
                required=True,
                choices=['demote', 'promote', 'force_promote', 'clear_promotion_token'],
            ),
            new_primary=dict(type='str', default=''),
            promotion_token=dict(type='str', default='', no_log=True),
            token_wait_timeout=dict(type='int', default=150),
            token_poll_interval=dict(type='int', default=5),
            reconciliation_wait=dict(type='int', default=10),
        ),
        required_if=[
            ('operation', 'demote', ['new_primary']),
            ('operation', 'promote', ['new_primary', 'promotion_token']),
            ('operation', 'force_promote', ['new_primary']),
        ],
        supports_check_mode=False,
    )

    helper = create_helper(module)

    namespace = module.params['namespace']
    cluster_name = module.params['cluster_name']
    operation = module.params['operation']

    if operation == 'clear_promotion_token':
        result = clear_promotion_token(module, helper, namespace, cluster_name)
    elif operation == 'demote':
        result = demote_primary(
            module, helper, namespace, cluster_name,
            module.params['new_primary'],
            module.params['token_wait_timeout'],
            module.params['token_poll_interval'],
        )
    elif operation == 'promote':
        result = promote_replica(
            module, helper, namespace, cluster_name,
            module.params['new_primary'],
            module.params['promotion_token'],
            module.params['reconciliation_wait'],
        )
    elif operation == 'force_promote':
        result = force_promote_replica(
            module, helper, namespace, cluster_name,
            module.params['new_primary'],
            module.params['reconciliation_wait'],
        )

    module.exit_json(**result)


if __name__ == '__main__':
    main()
